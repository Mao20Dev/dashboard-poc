import {test,expect} from '@playwright/test'
test('home has one entry to Sonnet, retains conversation and presents real priorities',async({page})=>{
 const sent:any[]=[]
 await page.route('**/api/v1/ai/chat',async route=>{
  if(route.request().method()==='GET')return route.fulfill({json:{enabled:true,model:'test',daily_limit:20,used_today:0}})
  sent.push(route.request().postDataJSON())
  return route.fulfill({json:{answer:'Datos clave:\nM-109 tiene señales que requieren revisión.\n\nRecomendación:\nContrasta el cambio con operación.',model:'test',sources:[{id:'m109',meter_id:'M-109',label:'Medidor M-109'}],cached:true}})
 })
 await page.emulateMedia({reducedMotion:'reduce'});await page.goto('/')
 await page.getByRole('button',{name:'Entrar a la demo',exact:true}).click()
 await expect(page.locator('.home-meter')).toHaveCount(12)
 await expect(page.locator('.chat-launcher,.assistant-home')).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Analizar con IA',exact:true})).toHaveCount(1)
 await expect(page.locator('.decision-card')).toHaveCount(3)
 await expect(page.locator('.decision-card').first()).toContainText('M-109')
 await expect(page.locator('.home-indicators .kpi')).toHaveCount(3)
 await expect(page.locator('.recharts-reference-line line')).toHaveAttribute('stroke-dasharray','5 5')
 const input=page.getByLabel('Pregúntale a Sonnet sobre tus datos')
 await input.fill('¿Qué medidor necesita atención?');await input.press('Enter')
 await expect(page.locator('.chat-message.assistant')).toHaveCount(1)
 expect(sent).toHaveLength(1);expect(sent[0].meter_id).toBe('');expect(sent[0].history).toEqual([])
 await page.getByRole('button',{name:'Cerrar chat'}).click()
 await expect(input).toBeFocused()
 await input.fill('¿Qué reviso después?');await input.press('Enter')
 await expect(page.locator('.chat-message.assistant')).toHaveCount(2)
 expect(sent).toHaveLength(2);expect(sent[1].history).toHaveLength(2)
 await page.getByRole('button',{name:'Cerrar chat'}).click()
 await page.setViewportSize({width:390,height:844})
 await expect(page.locator('.home-page')).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await input.fill('Compara los medidores');await input.press('Enter')
 await expect(page.locator('.chat-message.assistant')).toHaveCount(3)
 const panel=await page.locator('.chat-panel').boundingBox()
 expect(panel?.x).toBe(0);expect(panel?.width).toBe(390)
})
