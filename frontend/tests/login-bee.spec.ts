import {test,expect} from '@playwright/test'

test('bee responds to the cursor, changes theme and disposes when entering the demo',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 await page.goto('/')
 await expect(page.locator('html')).toHaveAttribute('data-theme','light')
 await expect(page.locator('.login-bee')).toHaveAttribute('data-state','ready')
 const viewport=page.locator('.bee-viewport')
 await expect(viewport.locator('canvas')).toBeVisible()
 const box=(await viewport.boundingBox())!
 await page.mouse.move(box.x+box.width/2,box.y+box.height/2)
 await expect(viewport).toHaveAttribute('data-reacting','true')
 await expect(page.getByRole('button',{name:/Pausar|Reanudar/})).toHaveCount(0)
 await page.mouse.move(10,10)
 await expect(viewport).toHaveAttribute('data-reacting','false')
 await page.getByRole('button',{name:'Cambiar a tema oscuro'}).click()
 await expect(viewport).toHaveAttribute('data-theme','dark')
 await expect(viewport).toHaveAttribute('data-motion','active')
 await page.getByRole('button',{name:'Entrar a la demo',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Hola, Uribe.'})).toBeVisible()
 await expect(page.locator('.login-bee')).toHaveCount(0)
 expect(errors).toEqual([])
})

test('mobile respects reduced motion and stacks the bee above the login',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/')
 const scene=page.locator('.login-bee'),viewport=page.locator('.bee-viewport')
 await expect(scene).toHaveAttribute('data-state','ready')
 await scene.scrollIntoViewIfNeeded()
 await expect(viewport).toHaveAttribute('data-motion','paused')
 await expect(page.getByRole('button',{name:/Pausar|Reanudar/})).toHaveCount(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 const sceneY=await scene.evaluate(e=>e.getBoundingClientRect().top)
 const loginY=await page.locator('.demo-button').evaluate(e=>e.getBoundingClientRect().bottom)
 expect(sceneY).toBeLessThan(loginY)
 await page.getByRole('button',{name:'Cambiar a tema oscuro'}).click()
 await scene.scrollIntoViewIfNeeded()
 await expect(viewport).toHaveAttribute('data-theme','dark')
 await expect(viewport).toHaveAttribute('data-motion','paused')
})

test('unavailable model shows a static bee and still allows demo access',async({page})=>{
 await page.route('**/models/bee.glb',route=>route.abort())
 await page.goto('/')
 await expect(page.locator('.login-bee')).toHaveAttribute('data-state','fallback')
 await expect(page.locator('.bee-static svg')).toBeVisible()
 await expect(page.locator('.bee-motion-toggle')).toHaveCount(0)
 await page.getByRole('button',{name:'Entrar a la demo',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Hola, Uribe.'})).toBeVisible()
})
