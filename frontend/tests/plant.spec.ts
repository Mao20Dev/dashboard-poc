import {test,expect} from './fixtures'

test.use({viewport:{width:1600,height:1050}})

test('baked plant uses live meters, sleeps at rest, follows camera and navigates inside the app',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 const assets:string[]=[];page.on('request',r=>{if(r.url().includes('/models/plant/'))assets.push(r.url())})
 await page.goto('/')
 await page.getByRole('button',{name:'Entrar a la demo',exact:true}).click()
 await expect(page.locator('.home-page')).toBeVisible()
 expect(assets).toHaveLength(0)
 await page.locator('.sidebar').getByRole('link',{name:'Medidores',exact:true}).click()
 const energy=await page.locator('.meters-table tbody tr').filter({hasText:'M-109'}).locator('.consumption-value').innerText()
 await page.getByRole('button',{name:'Vista de planta',exact:true}).click()
 const plant=page.locator('.eq-plant')
 await expect(plant).toHaveAttribute('data-ready','true',{timeout:45000})
 await expect(plant.locator('canvas')).toHaveCount(1)
 await expect(page.locator('.eq-plant-node')).toHaveCount(12)
 await plant.scrollIntoViewIfNeeded();await page.waitForTimeout(1200)
 const frames=await plant.getAttribute('data-frames')
 await page.waitForTimeout(500);expect(await plant.getAttribute('data-frames')).toBe(frames)
 const node=page.getByRole('link',{name:'Ver medidor M-109',exact:true})
 await node.hover();await expect(page.locator('.eq-plant-card')).toContainText(energy)
 expect(await plant.getAttribute('data-frames')).toBe(frames)
 await page.waitForTimeout(250);await page.screenshot({path:'test-results/plant-day.png',fullPage:true})
 await page.keyboard.press('Escape');await expect(page.locator('.eq-plant-card')).toHaveCount(0)
 const before=await node.boundingBox(),box=await plant.boundingBox()
 await page.mouse.move(box!.x+box!.width*.83,box!.y+box!.height*.78);await page.mouse.down();await page.mouse.move(box!.x+box!.width*.83-100,box!.y+box!.height*.78-10,{steps:12});await page.mouse.up();await page.waitForTimeout(700)
 const after=await node.boundingBox();expect(Math.abs(before!.x-after!.x)).toBeGreaterThan(5)
 await page.getByRole('button',{name:'Restablecer vista de planta'}).click()
 await page.getByRole('button',{name:'Críticos · 2',exact:true}).click()
 await expect(page.locator('.eq-plant-node')).toHaveCount(2)
 await page.getByLabel('Buscar medidor').fill('M-112');await expect(page.locator('.eq-plant-node')).toHaveCount(1)
 await page.getByLabel('Buscar medidor').fill('');await page.getByRole('button',{name:'Todos · 12',exact:true}).click()
 await page.getByRole('button',{name:'Cambiar a tema oscuro'}).click()
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');await page.waitForTimeout(1400)
 await page.screenshot({path:'test-results/plant-night.png',fullPage:true})
 await node.focus();await expect(page.locator('.eq-plant-card')).toBeVisible()
 await page.getByRole('link',{name:'Abrir medidor',exact:true}).click()
 await expect(page.locator('.meter-page h1')).toContainText('M-109')
 await expect(page.locator('.eq-plant-card')).toHaveCount(0)
 await page.locator('.sidebar').getByRole('link',{name:'Medidores',exact:true}).click()
 await page.getByRole('button',{name:'Vista de planta',exact:true}).click()
 await expect(plant).toHaveAttribute('data-ready','true')
 await page.getByRole('button',{name:'Tabla',exact:true}).click()
 await expect(page.locator('.meters-table tbody tr')).toHaveCount(12)
 await expect(plant).toHaveCount(0)
 expect(errors).toEqual([])
})

test('plant card fits touch screens and supports direct detail navigation',async({browser,baseURL})=>{
 const context=await browser.newContext({baseURL,viewport:{width:390,height:844},isMobile:true,hasTouch:true})
 const page=await context.newPage();await page.goto('/')
 await page.getByRole('button',{name:'Entrar a la demo',exact:true}).click()
 await expect(page.locator('.home-page')).toBeVisible();await page.goto('/#/meters')
 await page.getByRole('button',{name:'Vista de planta',exact:true}).click()
 await expect(page.locator('.eq-plant')).toHaveAttribute('data-ready','true')
 await page.getByRole('link',{name:'Ver medidor M-109',exact:true}).tap()
 await page.waitForTimeout(500);const card=page.locator('.eq-plant-card');await expect(card).toBeVisible()
 const rect=await card.boundingBox();expect(rect!.x).toBeGreaterThanOrEqual(0);expect(rect!.x+rect!.width).toBeLessThanOrEqual(390);expect(rect!.y+rect!.height).toBeLessThanOrEqual(844)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.getByRole('link',{name:'Abrir medidor',exact:true}).tap();await expect(page.locator('.meter-page h1')).toContainText('M-109')
 await context.close()
})
