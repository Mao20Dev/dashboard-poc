import {test,expect} from '@playwright/test'

test('custom selectors support keyboard, dismissal, themes and mobile without incidental analysis',async({page})=>{
 let calls=0
 await page.goto('/');await page.locator('.demo-button').click();await expect(page.locator('.home-page')).toBeVisible()
 const run=await (await page.request.get('/api/v1/ai/analysis/latest')).json()
 await page.route('**/api/v1/ai/analyze',async route=>{calls++;const body=route.request().postDataJSON();expect(body.cached_only).toBe(true);await route.fulfill({json:{...run,provider:body.provider}})})
 await page.locator('.sidebar nav a[href="#/meters"]').click()
 const select=page.getByRole('combobox',{name:'Proveedor de IA'})
 await select.click();await expect(page.getByRole('listbox',{name:'Proveedor de IA'})).toBeVisible()
 await expect(page.getByRole('option')).toHaveCount(3)
 await expect(page.getByRole('option',{selected:true})).toHaveCount(1)
 await page.keyboard.press('ArrowDown');expect(calls).toBe(0)
 await page.keyboard.press('Escape');await expect(page.getByRole('listbox')).toHaveCount(0);await expect(select).toBeFocused()
 await select.click();await page.locator('.meters-heading h1').click();await expect(page.getByRole('listbox')).toHaveCount(0)
 await select.focus();await page.keyboard.press('ArrowDown');await page.keyboard.press('g');await page.keyboard.press('Enter')
 await expect(select).toContainText('GPT');expect(calls).toBe(run.provider==='openai'?0:1)
 await select.click();await page.screenshot({path:'../analisis/select-light.png'})
 await page.keyboard.press('Tab');await expect(page.getByRole('listbox')).toHaveCount(0)
 await page.getByRole('button',{name:'Cambiar a tema oscuro'}).click();await select.click()
 await page.screenshot({path:'../analisis/select-dark.png'})
 await page.keyboard.press('Escape')
 await page.setViewportSize({width:390,height:844});await select.click()
 const rect=await page.locator('.soft-select-menu').boundingBox();expect(rect!.x).toBeGreaterThanOrEqual(12);expect(rect!.x+rect!.width).toBeLessThanOrEqual(390)
 await page.keyboard.press('Escape')
 await page.getByRole('link',{name:'Ver M-109',exact:true}).click()
 const variable=page.getByRole('combobox',{name:'Variable del gráfico'})
 await variable.click();await page.getByRole('option').filter({has:page.locator('strong',{hasText:'Corriente'})}).click()
 await expect(page.locator('.meter-timeline .detail-panel-heading')).toContainText('Corriente por hora · A')
 await expect(page.locator('.meter-timeline select')).toHaveCount(0)
})
