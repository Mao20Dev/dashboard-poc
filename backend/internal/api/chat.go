type ChatMessage struct {
	Role    string `json:"role"`
	Content string `json:"content"`
}
type ChatRequest struct {
	Message string        `json:"message"`
	MeterID string        `json:"meter_id"`
	History []ChatMessage `json:"history"`
}
type ChatSource struct {
	ID      string `json:"id"`
	Label   string `json:"label"`
	MeterID string `json:"meter_id,omitempty"`
}
type ChatResponse struct {
	Answer    string       `json:"answer"`
	Sources   []ChatSource `json:"sources"`
	Model     string       `json:"model"`
	Cached    bool         `json:"cached"`
	CreatedAt time.Time    `json:"created_at"`
}

func requestTimeout(path string) time.Duration {
	if path == "/api/v1/ai/chat" {
		return 45 * time.Second
	}
	return 20 * time.Second
}
func (a *API) chatStatus(w http.ResponseWriter, r *http.Request) {
	c, configured := a.Providers.Resolve("claude")
	model := ""
	if configured {
		model = c.ModelName()
	}
	limit := a.DB.ChatDailyLimit
	if limit <= 0 {
		limit = 20
	}
	var used int
	if err := a.DB.Pool.QueryRow(r.Context(), `SELECT count(*) FROM chat_requests WHERE actor=$1 AND created_at>=date_trunc('day',now() AT TIME ZONE 'UTC') AT TIME ZONE 'UTC'`, r.Context().Value(actorKey)).Scan(&used); err != nil {
		fail(w, err)
		return
	}
	send(w, 200, map[string]any{"enabled": a.DB.ChatEnabled && configured, "model": model, "daily_limit": limit, "used_today": used, "max_output_tokens": 1000})
}
func validChatRequest(b ChatRequest) bool {
	if len(strings.TrimSpace(b.Message)) < 2 || len(b.Message) > 2000 || len(b.MeterID) > 40 || len(b.History) > 6 {
		return false
	}
	size := 0
	for _, h := range b.History {
		if h.Role != "user" && h.Role != "assistant" {
			return false
		}
		if len(h.Content) > 6000 {
			return false
		}
		size += len(h.Content)
	}
	return size <= 14000
}

// Retrieval uses typed SQL data and the existing deterministic engine, never SQL generated by the LLM.
func chatContext(in domain.Input, fs []domain.Finding, ms []Meter, selected string) ([]any, map[string]ChatSource) {
	records := []any{}
	sources := map[string]ChatSource{}
	loc, _ := time.LoadLocation(in.Timezone)
	groups := engine.Groups(in)
	for _, m := range ms {
		rs := groups[m.ID]
		total, peak, minPF := 0.0, 0.0, 1.0
		var peakAt time.Time
		for _, r := range rs {
			total += r.Consumption
			if r.Consumption > peak {
				peak = r.Consumption
				peakAt = r.Timestamp
			}
			if r.PowerFactor < minPF {
				minPF = r.PowerFactor
			}
		}
		profile := engine.BuildProfile(rs, engine.DefaultConfig(), loc)
		sourceID := "meter:" + m.ID
		sources[sourceID] = ChatSource{ID: sourceID, Label: m.ID + " · lecturas y referencia", MeterID: m.ID}
		record := map[string]any{"source_id": sourceID, "summary_last_24h": m, "electrical_last_reading": electrical(rs, profile, loc), "period_energy_kwh": total, "period_start": rs[0].Timestamp, "period_end_exclusive": rs[len(rs)-1].Timestamp.Add(time.Hour), "peak_hour_average_kw": peak, "peak_hour_start": peakAt, "minimum_power_factor": minPF}
		if selected == m.ID {
			record["daily_energy"] = dailyHistory(rs, profile, loc)
		}
		records = append(records, record)
	}
	for _, f := range fs {
		evidence := append([]domain.Evidence(nil), f.Evidence...)
		for i := range evidence {
			evidence[i].SampleTimestamps = nil
		}
		id := "finding:" + f.ID
		sources[id] = ChatSource{ID: id, Label: f.MeterID + " · evidencia del hallazgo", MeterID: f.MeterID}
		records = append(records, map[string]any{"source_id": id, "meter_id": f.MeterID, "type": f.Type, "severity": f.Severity, "start": f.Start, "end_exclusive": f.End, "evidence": evidence, "events": f.RelatedEvents, "saved_interpretation": f.Explanation.Summary, "interpretation_provider": f.Explanation.Source})
	}
	return records, sources
}
func (a *API) chat(w http.ResponseWriter, r *http.Request) {
	var b ChatRequest
	if !decode(w, r, &b) {
		return
	}
	b.Message = strings.TrimSpace(b.Message)
	if !validChatRequest(b) {
		problem(w, 400, "invalid_chat", "Escribe una pregunta de hasta 2.000 caracteres. El contexto de conversación es demasiado largo o inválido.")
		return
	}
	c, configured := a.Providers.Resolve("claude")
	if !configured {
		problem(w, 503, "chat_unavailable", "Sonnet no está configurado para conversar.")
		return
	}
	in, fs, ms, err := a.state(r.Context())
	if err != nil {
		fail(w, err)
		return
	}
	if b.MeterID != "" {
		found := false
		for _, m := range ms {
			if m.ID == b.MeterID {
				found = true
			}
		}
		if !found {
			fail(w, store.ErrNotFound)
			return
		}
	}
	records, sources := chatContext(in, fs, ms, b.MeterID)
	payload, err := json.Marshal(map[string]any{"question": b.Message, "selected_meter": b.MeterID, "conversation": b.History, "records": records, "timezone": in.Timezone, "dataset_context": "Consumo de 12 medidores; hay un evento de nueva línea de producción. Sin topología ni identificación física de máquinas. Intervalos de una hora."})
	if err != nil {
		fail(w, err)
		return
	}
	if len(payload) > 80000 {
		problem(w, 413, "context_too_large", "El contexto supera el límite de esta conversación.")
		return
	}
	actor := r.Context().Value(actorKey).(string)
	sum := sha256.Sum256(append([]byte(explain.ChatVersion+"|"+c.ModelName()+"|"+actor+"|"), payload...))
	key := hex.EncodeToString(sum[:])
	cached, err := a.DB.ReserveChat(r.Context(), key, actor)
	switch {
	case errors.Is(err, store.ErrAIRequestsDisabled):
		problem(w, 409, "chat_disabled", "Las nuevas consultas del chat están desactivadas.")
		return
	case errors.Is(err, store.ErrChatLimit):
		problem(w, 429, "chat_daily_limit", "Alcanzaste el límite diario de consultas nuevas. Las respuestas guardadas siguen disponibles.")
		return
	case errors.Is(err, store.ErrChatPending):
		problem(w, 409, "chat_pending", "Esta consulta ya fue enviada o hay una respuesta en curso. No se repite para evitar un cobro duplicado.")
		return
	case errors.Is(err, store.ErrChatFailed):
		problem(w, 409, "chat_previous_failure", "Esta consulta falló antes. No se reenvía automáticamente para evitar otro cobro.")
		return
	case err != nil:
		fail(w, err)
		return
	}
	if cached != nil {
		var response ChatResponse
		if json.Unmarshal(cached, &response) != nil {
			problem(w, 500, "cache_invalid", "No se pudo recuperar la respuesta guardada.")
			return
		}
		response.Cached = true
		send(w, 200, response)
		return
	}
	valid := map[string]bool{}
	for id := range sources {
		valid[id] = true
	}
	// Once admitted, finish and cache even if the browser or proxy disconnects.
	// The independent deadline bounds this paid operation; no transport retry is performed.
	callContext, stopCall := context.WithTimeout(context.WithoutCancel(r.Context()), 45*time.Second)
	defer stopCall()
	answer, callErr := c.Chat(callContext, payload, valid)
	response := ChatResponse{Answer: answer.Answer, Sources: []ChatSource{}, Model: c.ModelName(), CreatedAt: time.Now()}
	for _, id := range answer.Sources {
		response.Sources = append(response.Sources, sources[id])
	}
	persist, cancel := context.WithTimeout(context.WithoutCancel(r.Context()), 5*time.Second)
	defer cancel()
	err = a.DB.FinishChat(persist, key, response, callErr == nil)
	if err != nil {
		fail(w, err)
		return
	}
	if callErr != nil {
		problem(w, 502, "chat_provider_error", "Sonnet no pudo completar la respuesta. No se hizo un reintento automático.")
		return
	}
	send(w, 200, response)
}
